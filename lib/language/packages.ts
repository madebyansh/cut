export type EffectKind = "pure" | "read" | "analyze" | "generate" | "external";
export type NodeDomain = "visual" | "audio" | "av" | "data" | "output";
export type PackageCompileTimeLowering = "record" | "timeline-edit-operation" | "anchored-spatial-call" | "data-bar-layout" | "data-bar-targets" | "data-format-number" | "data-query-record" | "data-query-plan" | "responsive-stack-plan" | "transcript-media-authority" | "transcript-edit" | "image-sequence-asset";

export type PackageParameter = {
  name: string;
  type: string;
  optional?: boolean;
  default?: unknown;
  values?: readonly string[];
};

export type PackageSymbol = {
  name: string;
  kind: "function" | "component" | "value";
  parameters?: PackageParameter[];
  returns: string;
  domain?: NodeDomain;
  children?: "none" | "visual" | "audio" | "av" | "any";
  effect: EffectKind;
  openNamed?: boolean;
  native?: string;
  /** Pure compile-time construction that must disappear into ordinary IR values. */
  lowering?: PackageCompileTimeLowering;
  documentation: string;
};

export type CutPackageManifest = {
  specifier: string;
  version: string;
  symbols: Record<string, PackageSymbol>;
  apiIntegrity: string;
  implementationIntegrity: string;
  integrity: string;
};

function symbol(value: Omit<PackageSymbol, "effect"> & { effect?: EffectKind }): PackageSymbol {
  const result: PackageSymbol = { effect: "pure", ...value };
  if (result.lowering !== undefined) {
    const parameters = result.parameters ?? [], names = parameters.map((parameter) => parameter.name);
    if (result.kind !== "function" || result.effect !== "pure" || result.native !== undefined || result.domain !== undefined || result.children !== undefined || result.openNamed !== undefined) {
      throw new Error(`CUT package compile-time lowering ${result.name} must be a pure function without native, domain, child, or open-named runtime semantics.`);
    }
    if (!parameters.length || parameters.some((parameter) => parameter.default !== undefined)) {
      throw new Error(`CUT package compile-time lowering ${result.name} must declare at least one parameter and cannot use manifest-only defaults.`);
    }
    if (new Set(names).size !== names.length || names.some((name) => !/^[A-Za-z_][A-Za-z0-9_]*$/.test(name) || ["__proto__", "prototype", "constructor"].includes(name))) {
      throw new Error(`CUT package compile-time lowering ${result.name} has duplicate or unsafe field names.`);
    }
    const specialized = result.lowering === "record" || result.lowering === "timeline-edit-operation" || result.lowering === "anchored-spatial-call" || result.lowering === "data-query-record" || result.lowering === "data-query-plan" ? undefined : {
      "data-bar-layout": { name: "barLayout", returns: "BarLayout", parameters: ["data", "x", "y", "width", "height", "min", "max", "gap", "padding"] },
      "data-bar-targets": { name: "barTargets", returns: "List<BarMarkTransform>", parameters: ["layout", "targets"] },
      "data-format-number": { name: "formatNumber", returns: "String", parameters: ["value", "decimals", "suffix"] },
      "responsive-stack-plan": { name: "responsiveStackPlan", returns: "ResponsiveStackPlan", parameters: ["weights", "safeX", "safeY", "gap"] },
      "transcript-media-authority": {
        name: "transcriptMedia",
        returns: "TranscriptMediaAuthority",
        parameters: ["transcript", "audio", "audioStream", "video", "videoStream", "videoFrameRate", "videoDuration", "audioAt", "videoAt", "videoRate"],
      },
      "transcript-edit": { name: "transcriptEdit", returns: "TranscriptEdit", parameters: ["transcript", "source", "from", "through", "at", "link", "media"] },
      "image-sequence-asset": {
        name: "imageSequence",
        returns: "ImageSequenceAsset",
        parameters: ["manifest", "frames", "width", "height", "frameRate", "frameCount"],
      },
    }[result.lowering];
    if (specialized && (result.name !== specialized.name
      || result.returns !== specialized.returns
      || names.length !== specialized.parameters.length
      || names.some((name, index) => name !== specialized.parameters[index])
      || (result.lowering === "transcript-edit"
        ? parameters.some((parameter, index) => Boolean(parameter.optional) !== (index === 5 || index === 6))
        : parameters.some((parameter) => parameter.optional)))) {
      throw new Error(`CUT package compile-time lowering ${result.lowering} has an invalid public signature.`);
    }
    if (result.lowering === "transcript-media-authority") {
      const types = ["TranscriptAsset", "AudioAsset", "Number", "VideoAsset", "Number", "Number", "Time", "Time", "Time", "Number"];
      if (parameters.some((parameter, index) => parameter.type !== types[index]
        || parameter.values !== undefined)) {
        throw new Error("CUT package compile-time lowering transcript-media-authority has an invalid public signature.");
      }
    }
    if (result.lowering === "transcript-edit") {
      const types = ["TranscriptAsset", "AudioAsset", "String", "String", "Time", "String", "TranscriptMediaAuthority"];
      if (parameters.some((parameter, index) => parameter.type !== types[index]
        || parameter.values !== undefined)) {
        throw new Error("CUT package compile-time lowering transcript-edit has an invalid public signature.");
      }
    }
    if (result.lowering === "image-sequence-asset") {
      const types = ["DataAsset", "List<ImageAsset>", "Length", "Length", "Number", "Number"];
      if (parameters.some((parameter, index) => parameter.type !== types[index]
        || parameter.values !== undefined || parameter.optional)) {
        throw new Error("CUT package compile-time lowering image-sequence-asset has an invalid public signature.");
      }
    }
    if (result.lowering === "anchored-spatial-call") {
      const contracts: Readonly<Record<string, Readonly<{ returns: string; parameters: readonly string[] }>>> = Object.freeze({
        visualAnchor: { returns: "VisualAnchor", parameters: ["owner", "local"] },
        compositionOffset: { returns: "SpatialPoint", parameters: ["point", "by"] },
        anchoredLineTo: { returns: "AnchoredLinePathSegment", parameters: ["to"] },
        anchoredCubicTo: { returns: "AnchoredCubicPathSegment", parameters: ["control1", "control2", "to"] },
        anchoredPath: { returns: "AnchoredPathGeometry", parameters: ["start", "segments", "closed"] },
      });
      const contract = contracts[result.name];
      if (!contract || result.returns !== contract.returns
        || parameters.some((parameter) => parameter.optional)
        || names.length !== contract.parameters.length
        || names.some((name, index) => name !== contract.parameters[index])) {
        throw new Error(`CUT package compile-time lowering anchored-spatial-call has an invalid public signature for ${result.name}.`);
      }
    }
  }
  return result;
}

/** Test/audit view of the generated canonical lib-root-relative implementation closure. */
export function builtinPackageImplementationFiles(specifier: CutBuiltinPackageSpecifier) {
  return [...readCutBuiltinImplementationClosure().packages[specifier]];
}

/** Test/audit recomputation hook; production manifests always use the canonical baseline identity. */
export function fingerprintPackageImplementation(
  specifier: CutBuiltinPackageSpecifier,
  dependencies?: ReferenceDependencyIdentity,
  sourceOverrides?: ReadonlyMap<string, string | Buffer>,
) {
  return createCutBuiltinImplementationIdentity(specifier, {
    ...(dependencies === undefined ? {} : { dependencies }),
    ...(sourceOverrides === undefined ? {} : { sourceOverrides }),
  }).integrity;
}

function manifest(specifier: CutBuiltinPackageSpecifier, version: string, symbols: Record<string, PackageSymbol>): CutPackageManifest {
  const apiIntegrity = hash({ specifier, version, symbols });
  const implementationIntegrity = createCutBuiltinImplementationIdentity(specifier).integrity;
  return { specifier, version, symbols, apiIntegrity, implementationIntegrity, integrity: hash({ apiIntegrity, implementationIntegrity }) };
}

