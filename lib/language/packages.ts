export const builtinPackages = new Map<string, CutPackageManifest>([core, visual, audio, edit, motion, geo, dataPackage, diagram, documentary].map((item) => [item.specifier, item]));

const nativePackageSpecifiers = new Map<string, string>();
for (const package_ of builtinPackages.values()) {
  for (const symbol of Object.values(package_.symbols)) {
    if (!symbol.native) continue;
    const existing = nativePackageSpecifiers.get(symbol.native);
    if (existing && existing !== package_.specifier) throw new Error(`CUT native operation ${symbol.native} is exported by both ${existing} and ${package_.specifier}.`);
    nativePackageSpecifiers.set(symbol.native, package_.specifier);
  }
}

/** Resolve a built-in executable operation to the package identity that owns it. */
export function packageSpecifierForNative(native: string) { return nativePackageSpecifiers.get(native); }

export const implicitSymbols: Record<string, PackageSymbol> = core.symbols;

export function packageSymbol(specifier: string, name: string) {
  return builtinPackages.get(specifier)?.symbols[name];
}

export function packageManifestsFor(specifiers: Iterable<string>) {
  return [...new Set(specifiers)].map((specifier) => builtinPackages.get(specifier)).filter((value): value is CutPackageManifest => Boolean(value));
}
